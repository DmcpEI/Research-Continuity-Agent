"""Publish the test-split scorecard from one harness run.

    uv run python eval/harness.py --split test
    uv run python eval/scorecard.py eval/results/run_<timestamp>.json

Refuses a run that cannot stand for the shipped system (not the test split, dirty tree,
degraded index, an errored question, a non-default setting). Otherwise writes
eval/scorecard.json and rewrites the generated block in README.md and docs/EVAL.md, so
the numbers in the docs are never typed by hand.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import statistics
import sys
from pathlib import Path
from typing import Any

from rca.config.settings import Settings
from rca.telemetry.provenance import RESULT_SETTINGS

START = "<!-- scorecard:start (generated by eval/scorecard.py from eval/scorecard.json) -->"
END = "<!-- scorecard:end -->"
DOCS = (Path("README.md"), Path("docs") / "EVAL.md")
CARD = Path("eval") / "scorecard.json"


def wilson_interval(hits: int, n: int, z: float = 1.96) -> tuple[float, float]:
    # same formula as eval/run_ablations.py
    if n == 0:
        return 0.0, 0.0
    p = hits / n
    denominator = 1 + z**2 / n
    center = (p + z**2 / (2 * n)) / denominator
    margin = (z * (p * (1 - p) / n + z**2 / (4 * n**2)) ** 0.5) / denominator
    return max(0.0, center - margin), min(1.0, center + margin)


# Trace warnings that are normal behaviour; any other warning means a component fell back.
NORMAL_WARNINGS = (
    "rewrite skipped:",
    "failure:",
    "rerank gate:",
    "empty retrieval",
    "rewritten retrieval produced empty context",
)
# Recorded for provenance but unused by grounded chat on the default (Ollama) backend.
NOT_CHAT_SETTINGS = {"agent_model", "openai_chat_model", "openai_embed_model"}
GOLDEN = Path("eval") / "golden.json"
TEST_SPLIT = Path("eval") / "splits" / "test.json"


def check_run(run: dict[str, Any], root: Path = Path(".")) -> list[str]:
    """Reasons this run cannot be published; empty when it can."""
    problems = []
    provenance = run.get("provenance") or {}
    results = run.get("results") or []
    run_config = run.get("run_config") or {}
    if run.get("split") != "test" or run.get("dataset_kind") != "golden":
        problems.append(f"not the golden test split (split={run.get('split')!r})")
    if not results or len(results) != run.get("cases"):
        problems.append("missing or incomplete results")

    golden_sha = hashlib.sha256((root / GOLDEN).read_bytes()).hexdigest()
    test_ids = json.loads((root / TEST_SPLIT).read_text(encoding="utf-8"))["ids"]
    if run.get("golden_sha256") != golden_sha:
        problems.append(f"questions not read from the committed {GOLDEN}")
    if sorted(run.get("question_ids") or []) != sorted(test_ids) or sorted(
        r.get("id") for r in results
    ) != sorted(test_ids):
        problems.append(f"questions are not exactly those in {TEST_SPLIT}")

    if (provenance.get("code") or {}).get("dirty") is not False:
        problems.append("run not made from a clean, committed tree")
    if provenance.get("index_degraded_during_run") is not False:
        problems.append("vector index degraded during the run")
    if (provenance.get("index_start") or {}).get("backend") != "chroma":
        problems.append("vector index not on chroma at the start")
    for field, value in (
        ("run_config.resolved_model", run_config.get("resolved_model")),
        ("provenance.code.commit", (provenance.get("code") or {}).get("commit")),
        (
            "provenance.corpus.corpus_version",
            (provenance.get("corpus") or {}).get("corpus_version"),
        ),
        ("provenance.reranker", provenance.get("reranker")),
    ):
        if not value:
            problems.append(f"{field} not recorded")
    if run_config.get("resolved_rewrite_model") != run_config.get("resolved_model"):
        problems.append("query rewrite model overridden")

    errored = [r.get("id") for r in results if r.get("outcome") == "error"]
    if errored:
        problems.append(f"questions errored: {errored}")
    unrecorded = [r.get("id") for r in results if "warnings" not in r]
    if unrecorded:
        problems.append(f"no trace warnings recorded for {len(unrecorded)} questions")
    fell_back = {
        r.get("id"): [w for w in r.get("warnings") or [] if not w.startswith(NORMAL_WARNINGS)]
        for r in results
    }
    fell_back = {rid: warnings for rid, warnings in fell_back.items() if warnings}
    if fell_back:
        problems.append(f"components fell back during the run: {fell_back}")
    check_failed = [
        r.get("id") for r in results if "facts_check_failed" in r.get("failure_labels", [])
    ]
    if check_failed:
        problems.append(f"facts check failed on: {check_failed}")

    settings = provenance.get("settings") or {}
    for name in RESULT_SETTINGS:
        default = Settings.model_fields[name].default
        if name not in settings:
            problems.append(f"setting {name} not recorded")
        elif name not in NOT_CHAT_SETTINGS and settings[name] != default:
            problems.append(f"setting {name}={settings[name]!r}, shipped default is {default!r}")
    return problems


def proportion(hits: int, n: int) -> dict[str, Any]:
    lower, upper = wilson_interval(hits, n)
    return {"hits": hits, "n": n, "lower": round(lower, 3), "upper": round(upper, 3)}


def build_scorecard(run: dict[str, Any]) -> dict[str, Any]:
    results = run["results"]
    answerable = [r for r in results if r["answerable"]]
    negatives = [r for r in results if not r["answerable"]]
    answered = [r for r in answerable if not r["abstained"]]
    in_top5 = {
        r["id"]: bool(r["expected_sources"])
        and all(source in r["retrieved_sources"] for source in r["expected_sources"])
        for r in answerable
    }
    latencies = [r["latency_ms"] / 1000.0 for r in results]
    provenance = run["provenance"]
    model = run["run_config"]["resolved_model"]
    return {
        "run": run["timestamp"],
        "split": run["split"],
        "questions": len(results),
        "model": model,
        "model_digest": ((provenance.get("models") or {}).get("models") or {}).get(model),
        "reranker": provenance["reranker"],
        "commit": provenance["code"]["commit"],
        "corpus_version": provenance["corpus"]["corpus_version"],
        "facts_check_enabled": provenance["settings"].get("facts_check_enabled"),
        "metrics": {
            "answered_with_expected_citation": proportion(
                sum(r["source_correct"] for r in answerable), len(answerable)
            ),
            "answerable_refused": proportion(
                sum(r["abstained"] for r in answerable), len(answerable)
            ),
            "unanswerable_refused": proportion(
                sum(r["abstained"] for r in negatives), len(negatives)
            ),
            "citation_precision": proportion(
                sum(r["source_correct"] for r in answered), len(answered)
            ),
            "retrieval_hit_at_5": proportion(sum(in_top5.values()), len(answerable)),
            "keyword_hit_rate": round(
                statistics.fmean(r["keyword_hits"] for r in answerable) if answerable else 0.0, 3
            ),
            "mean_seconds": round(statistics.fmean(latencies), 1),
            "median_seconds": round(statistics.median(latencies), 1),
        },
        "misses": {
            "answerable_refused": [r["id"] for r in answerable if r["abstained"]],
            "answered_without_expected_citation": [
                r["id"] for r in answered if not r["source_correct"]
            ],
            "unanswerable_answered": [r["id"] for r in negatives if not r["abstained"]],
            "retrieval_not_in_top5": [rid for rid, hit in in_top5.items() if not hit],
        },
    }


def _row(label: str, value: dict[str, Any]) -> str:
    hits, n = value["hits"], value["n"]
    rate = f" ({hits / n:.0%})" if n else ""
    return f"| {label} | `{hits}/{n}`{rate} | {value['lower']:.0%} to {value['upper']:.0%} |"


def render(card: dict[str, Any]) -> str:
    m = card["metrics"]
    answerable = m["answerable_refused"]["n"]
    misses = card["misses"]

    def ids(key: str) -> str:
        return ", ".join(f"`{i}`" for i in misses[key]) or "none"

    lines = [
        START,
        f"Held-out test split, {card['questions']} questions ({answerable} answerable, "
        f"{m['unanswerable_refused']['n']} unanswerable), shipped defaults: `{card['model']}` "
        f"for answers and query rewrites, facts check "
        f"{'on' if card['facts_check_enabled'] else 'off'}. Intervals are Wilson 95%.",
        "",
        "| Test split | Result | 95% interval |",
        "|---|---|---|",
        _row(
            "Answerable: answered, citing the expected paper", m["answered_with_expected_citation"]
        ),
        _row("Answerable: refused", m["answerable_refused"]),
        _row('Unanswerable: refused ("not in your papers")', m["unanswerable_refused"]),
        _row("When it answers: cites every expected paper", m["citation_precision"]),
        _row("Retrieval: expected paper in the top 5", m["retrieval_hit_at_5"]),
        f"| Answer keyword hit rate (answerable, mean) | `{m['keyword_hit_rate']:.3f}` | |",
        f"| Time per question | mean `{m['mean_seconds']:.1f} s`, median "
        f"`{m['median_seconds']:.1f} s` | |",
        "",
        f"Misses. Answerable refused: {ids('answerable_refused')}. Answered without the "
        f"expected citation: {ids('answered_without_expected_citation')}. Unanswerable "
        f"answered: {ids('unanswerable_answered')}. Expected paper not in the top 5: "
        f"{ids('retrieval_not_in_top5')}.",
        "",
        f"Run `{card['run']}`, commit `{card['commit'][:7]}`, corpus `{card['corpus_version']}`. "
        "Reproduce: `uv run python eval/harness.py --split test`, then "
        "`uv run python eval/scorecard.py eval/results/run_<timestamp>.json`.",
        END,
    ]
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        raise ValueError("expected exactly one scorecard block (start marker before end marker)")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    return before + block + after


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Publish the test-split scorecard from a run.")
    parser.add_argument("run_path")
    parser.add_argument(
        "--root",
        default=str(Path(__file__).resolve().parents[1]),
        help="Repo root holding eval/golden.json, eval/scorecard.json and the docs.",
    )
    args = parser.parse_args(argv)

    run = json.loads(Path(args.run_path).read_text(encoding="utf-8"))
    problems = check_run(run, Path(args.root))
    if problems:
        print("Not published:\n- " + "\n- ".join(problems), file=sys.stderr)
        return 1
    card = build_scorecard(run)
    block = render(card)
    root = Path(args.root)
    # Check every doc before writing any, so a missing marker leaves nothing half-updated.
    updated = {
        path: replace_block((root / path).read_text(encoding="utf-8"), block) for path in DOCS
    }
    (root / CARD).write_text(json.dumps(card, indent=2) + "\n", encoding="utf-8")
    for path, text in updated.items():
        (root / path).write_text(text, encoding="utf-8")
    print(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
